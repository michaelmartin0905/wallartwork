  <section class="sec sec--coal" aria-labelledby="process-title">
    <div class="wrap">
      <div class="sec__head">
        <div><p class="tag">How a wall comes together</p><h2 class="h2" id="process-title">From first email to <em>final reveal</em>.</h2></div>
        <p>Every project is different, but most follow the same five stages. The detail of each stage is agreed with you in writing before work begins.</p>
      </div>
      <ol class="steps">
        <li class="step"><span class="step__n">Stage 01</span><h3>Listen</h3><p>We learn what the space is for, who uses it, and the mood, story or references you have in mind.</p></li>
        <li class="step"><span class="step__n">Stage 02</span><h3>Survey</h3><p>Wall size, surface condition, light and access are reviewed so the design suits the real wall.</p></li>
        <li class="step"><span class="step__n">Stage 03</span><h3>Concept</h3><p>A design direction, palette and scale preview are shared with you for feedback and approval.</p></li>
        <li class="step"><span class="step__n">Stage 04</span><h3>Make</h3><p>The surface is prepared and the artwork is painted or installed according to the agreed plan.</p></li>
        <li class="step"><span class="step__n">Stage 05</span><h3>Reveal &amp; care</h3><p>A final walkthrough, plus practical guidance on cleaning and looking after the finished wall.</p></li>
      </ol>
    </div>
