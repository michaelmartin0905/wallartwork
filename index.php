  <section class="sec" aria-labelledby="brief-title">
    <div class="wrap brief">
      <div>
        <p class="tag">Before you commission</p>
        <h2 class="h2" id="brief-title">Six things that shape <em>every</em> wall.</h2>
        <div class="brief__grid">
          <div class="brief__item"><h3><i>i.</i> The surface</h3><p>Brick, plaster, drywall, concrete and textured render each need different preparation.</p></div>
          <div class="brief__item"><h3><i>ii.</i> The light</h3><p>Daylight, warm lamps and evening glare all change how colour and detail read.</p></div>
          <div class="brief__item"><h3><i>iii.</i> Scale &amp; distance</h3><p>A wall seen from a dining table needs a different level of detail from one seen across a street.</p></div>
          <div class="brief__item"><h3><i>iv.</i> Traffic &amp; touch</h3><p>Corridors, booth backs and entrances are touched often, which affects finishes and placement.</p></div>
          <div class="brief__item"><h3><i>v.</i> The story</h3><p>Brand, heritage, neighbourhood or a personal memory can anchor the concept.</p></div>
          <div class="brief__item"><h3><i>vi.</i> Timing</h3><p>When the space can be closed, cleared or worked in around opening hours.</p></div>
        </div>
