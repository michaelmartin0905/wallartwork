      <div>
        <p class="tag">Our approach</p>
        <h2 class="h2" id="approach-title">A wall is the largest canvas in the room.</h2>
        <p class="statement__big" style="margin-top:28px">It is also the most overlooked. We approach it the way a gallery approaches a hang — <mark>what the space is for</mark>, who moves through it, where the light falls, and what feeling should stay with people after they leave.</p>
        <div class="trio">
          <div><h3>Made for the room</h3><p>Scale, palette and placement are decided by the architecture, not dropped onto it.</p></div>
          <div><h3>One clear idea</h3><p>Each wall carries a single strong concept, so it reads instantly and rewards a closer look.</p></div>
          <div><h3>Considered surfaces</h3><p>Brick, plaster, drywall and concrete each behave differently; preparation is planned per wall.</p></div>
